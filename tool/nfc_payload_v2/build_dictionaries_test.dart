// tool/nfc_payload_v2/build_dictionaries_test.dart
//
// Builds the format 2 dictionaries from synthetic records and writes
// lib/src/core/nfc/nfc_payload_v2_dictionaries.dart. Not part of the test
// suite: it lives outside test/ and skips itself unless HWB_NFC_CORPUS names
// the corpus. See tool/nfc_payload_v2/README.md.
//
//   HWB_NFC_CORPUS=/path/corpus.jsonl \
//   fvm flutter test tool/nfc_payload_v2/build_dictionaries_test.dart

import 'dart:convert';
import 'dart:io';
import 'dart:math';
import 'dart:typed_data';

import 'package:crypto/crypto.dart' as crypto;
import 'package:flutter_test/flutter_test.dart';
import 'package:health_without_borders_frontend/src/core/nfc/nfc_guardian_alias.dart';
import 'package:health_without_borders_frontend/src/core/nfc/nfc_payload_v2.dart';

/// Size of each dictionary, in bytes. The guardian copy is several times
/// larger than the triage and gains up to the 32 KB DEFLATE window; the triage
/// gains little past 8 KB (see the measurements in ADR 005).
const int kTriageBytes = 8 * 1024;
const int kGuardianBytes = 32 * 1024;

/// Seed of the shuffle that picks which samples go in.
const int kSeed = 7;

const String kOutput = 'lib/src/core/nfc/nfc_payload_v2_dictionaries.dart';

Uint8List _concat(List<Uint8List> samples, int limit) {
  final List<Uint8List> shuffled = List<Uint8List>.of(samples)
    ..shuffle(Random(kSeed));
  final BytesBuilder out = BytesBuilder(copy: false);
  for (final Uint8List sample in shuffled) {
    if (out.length + sample.length > limit) break;
    out.add(sample);
  }
  return out.toBytes();
}

String _dartString(String name, Uint8List bytes) {
  final String b64 = base64Encode(bytes);
  final StringBuffer out = StringBuffer('const String $name =\n');
  for (int i = 0; i < b64.length; i += 72) {
    final int end = i + 72 < b64.length ? i + 72 : b64.length;
    out.write("    '${b64.substring(i, end)}'");
    out.write(end == b64.length ? ';\n' : '\n');
  }
  return out.toString();
}

void main() {
  final String? corpus = Platform.environment['HWB_NFC_CORPUS'];

  test(
    'build format 2 dictionaries',
    () {
      final List<Map<String, dynamic>> train = File(corpus!)
          .readAsLinesSync()
          .where((String l) => l.trim().isNotEmpty)
          .map((String l) => jsonDecode(l) as Map<String, dynamic>)
          .where((Map<String, dynamic> r) => r['split'] == 'train')
          .toList();
      expect(train, isNotEmpty, reason: 'El corpus no tiene registros train.');

      final List<Uint8List> triage = <Uint8List>[
        for (final Map<String, dynamic> r in train)
          NfcPayloadV2.typedCbor(
            (r['triage'] as Map<String, dynamic>),
            NfcPayloadKind.triage,
          ),
      ];
      final List<Uint8List> guardian = <Uint8List>[
        for (final Map<String, dynamic> r in train)
          NfcPayloadV2.typedCbor(
            aliasGuardianPayload(
              ((r['g'] as List<dynamic>)[3] as Map<String, dynamic>)['full']
                  as Map<String, dynamic>,
            ),
            NfcPayloadKind.guardian,
          ),
      ];
      final Uint8List triageDict = _concat(triage, kTriageBytes);
      final Uint8List guardianDict = _concat(guardian, kGuardianBytes);
      final String triageSha = crypto.sha256.convert(triageDict).toString();
      final String guardianSha = crypto.sha256.convert(guardianDict).toString();

      final StringBuffer src = StringBuffer()
        ..writeln('// lib/src/core/nfc/nfc_payload_v2_dictionaries.dart')
        ..writeln('//')
        ..writeln(
          '// GENERATED by tool/nfc_payload_v2/build_dictionaries_test.dart '
          'from',
        )
        ..writeln(
          '// ${train.length} synthetic training records (no patient data). '
          'Do not edit.',
        )
        ..writeln('//')
        ..writeln(
          '// A dictionary is part of the payload format: once a build writes '
          'with it,',
        )
        ..writeln(
          '// every later build must keep reading it. Add a new id for a new '
          'dictionary;',
        )
        ..writeln('// never change the bytes of an id that was written with.')
        ..writeln()
        ..writeln("import 'dart:convert';")
        ..writeln("import 'dart:typed_data';")
        ..writeln()
        ..writeln('/// Dictionary format 2 writes triages with.')
        ..writeln('const int kNfcV2TriageDictionaryId = 1;')
        ..writeln()
        ..writeln('/// Dictionary format 2 writes guardian copies with.')
        ..writeln('const int kNfcV2GuardianDictionaryId = 1;')
        ..writeln()
        ..writeln('/// SHA-256 of triage dictionary 1 (${triageDict.length} B).')
        ..writeln("const String kNfcV2TriageDictionary1Sha256 = '$triageSha';")
        ..writeln()
        ..writeln(
          '/// SHA-256 of guardian dictionary 1 (${guardianDict.length} B).',
        )
        ..writeln(
          "const String kNfcV2GuardianDictionary1Sha256 = '$guardianSha';",
        )
        ..writeln()
        ..writeln('/// Triage dictionary [id], or null when this build has none.')
        ..writeln('Uint8List? nfcV2TriageDictionary(int id) =>')
        ..writeln('    id == 1 ? _triage1 : null;')
        ..writeln()
        ..writeln(
          '/// Guardian-copy dictionary [id], or null when this build has none.',
        )
        ..writeln('Uint8List? nfcV2GuardianDictionary(int id) =>')
        ..writeln('    id == 1 ? _guardian1 : null;')
        ..writeln()
        ..writeln('final Uint8List _triage1 = base64Decode(_triage1Base64);')
        ..writeln('final Uint8List _guardian1 = base64Decode(_guardian1Base64);')
        ..writeln()
        ..write(_dartString('_triage1Base64', triageDict))
        ..writeln()
        ..write(_dartString('_guardian1Base64', guardianDict));

      File(kOutput).writeAsStringSync(src.toString());
      stdout.writeln(
        'triage: ${triageDict.length} B, sha256 $triageSha\n'
        'guardian: ${guardianDict.length} B, sha256 $guardianSha',
      );
    },
    skip: corpus == null || corpus.isEmpty
        ? 'Define HWB_NFC_CORPUS con el corpus sintético de la auditoría.'
        : false,
  );
}
